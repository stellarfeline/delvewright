//! **One sight rule, held by agreement** (spec-0112 §16 criterion 12).
//!
//! Whether a target is inside a camera's frame, and whether it is hidden there,
//! is answered once: [`delvec::compiler::framing::resolve_targets`], whose
//! building blocks are private to `compiler::framing`. Every consumer of that
//! answer is asked the same generated cases here, and the test is red on any
//! difference, naming the consumer. The consumers are enumerated from the call
//! graph of `resolve_targets` and of the `ResolvedTarget` it returns:
//!
//! - `manifest` — the frame manifest's `targets` and `out_of_frame`
//!   ([`delvec::compiler::framing::manifest`]), which `frames --campaign` and
//!   `edit` write;
//! - `snapshot` — the `shows` a `frames --campaign` frame's labels are stamped
//!   from ([`crate::cli::view::snapshot_frame`]);
//! - `edit` — the `shows` a batch frame's labels are stamped from
//!   ([`crate::cli::edit::batch_frame`]);
//! - `review` — a review shot's `shows` and `out_of_frame`, which the shot index
//!   and every review frame's manifest copy
//!   ([`delvec::compiler::view::review::frame_row`]);
//! - `stand-back` — whether a room camera still sees the anchor it stands back
//!   from ([`delvec::compiler::view::sight::anchor_in_sight`]).
//!
//! The cases are generated by a seeded SplitMix64 (ADR-0006: no unseeded RNG):
//! a random occupancy box with walls, a camera anywhere in or near it, and point
//! and box targets, some coinciding with blocks, some behind the eye.

#![cfg(test)]

use std::collections::{BTreeMap, BTreeSet};

use delvec::compiler::blockstate::BlockState;
use delvec::compiler::framing::{self, Camera, Target, VoxelGrid};
use serde_json::Value;

/// The generator's fixed seed.
const SEED: u64 = 0x5167_4854_0112_0012;
/// Cases generated.
const CASES: usize = 512;

struct SplitMix(u64);

impl SplitMix {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
    fn range(&mut self, lo: i32, hi: i32) -> i32 {
        lo + self.below((hi - lo + 1) as u64) as i32
    }
    fn unit(&mut self) -> f64 {
        (self.next() >> 11) as f64 / (1u64 << 53) as f64
    }
    fn real(&mut self, lo: f64, hi: f64) -> f64 {
        lo + (hi - lo) * self.unit()
    }
}

/// One generated case: a world, a camera on it, a square frame and targets.
struct Case {
    grid: VoxelGrid,
    cam: Camera,
    size: u32,
    targets: Vec<Target>,
}

const EDGE: i32 = 20;

fn case(rng: &mut SplitMix) -> Case {
    let mut blocks = BTreeMap::new();
    let density = rng.real(0.0, 0.2);
    for x in 0..EDGE {
        for y in 0..EDGE {
            for z in 0..EDGE {
                if rng.unit() < density {
                    blocks.insert([x, y, z], BlockState::new("minecraft:stone"));
                }
            }
        }
    }
    // Walls and floors: the occluders a frame is mostly made of.
    for _ in 0..rng.below(3) {
        let axis = rng.below(3) as usize;
        let at = rng.range(0, EDGE - 1);
        let (lo, hi) = (rng.range(0, EDGE / 2), rng.range(EDGE / 2, EDGE - 1));
        for a in lo..=hi {
            for b in lo..=hi {
                let mut c = [a, b, a];
                c[axis] = at;
                c[(axis + 1) % 3] = a;
                c[(axis + 2) % 3] = b;
                blocks.insert(c, BlockState::new("minecraft:deepslate"));
            }
        }
    }
    let grid = VoxelGrid::build(&blocks);
    let pos = [
        rng.real(-4.0, f64::from(EDGE) + 4.0),
        rng.real(-4.0, f64::from(EDGE) + 4.0),
        rng.real(-4.0, f64::from(EDGE) + 4.0),
    ];
    let cam = if rng.below(2) == 0 {
        Camera {
            pos,
            yaw: rng.real(0.0, 360.0),
            pitch: rng.real(-80.0, 80.0),
            fov: rng.real(30.0, 110.0),
        }
    } else {
        let at = [
            rng.real(0.0, f64::from(EDGE)),
            rng.real(0.0, f64::from(EDGE)),
            rng.real(0.0, f64::from(EDGE)),
        ];
        Camera::looking_at(pos, at, rng.real(30.0, 110.0))
    };
    let size = [16, 48, 96, 128][rng.below(4) as usize];
    let mut targets = Vec::new();
    for i in 0..rng.range(1, 12) {
        let min = [
            rng.range(-6, EDGE + 6),
            rng.range(-6, EDGE + 6),
            rng.range(-6, EDGE + 6),
        ];
        let id = format!("t{i}");
        if rng.below(2) == 0 {
            targets.push(Target::point(id, "anchor", String::new(), min));
        } else {
            let max = [
                min[0] + rng.range(0, 3),
                min[1] + rng.range(0, 3),
                min[2] + rng.range(0, 3),
            ];
            targets.push(Target {
                id,
                kind: "gate",
                area: "area/case".into(),
                min,
                max,
            });
        }
    }
    Case {
        grid,
        cam,
        size,
        targets,
    }
}

/// An answer in one form for every consumer: per target id, `None` when out of
/// frame, else its screen box and whether it is hidden.
type Answer = BTreeMap<String, Option<(Value, bool)>>;

/// Read an answer off a consumer's `shows`-shaped and `out_of_frame`-shaped
/// lists. A target listed twice, or listed by neither, is a difference.
fn answer_of(shows: &[Value], out: &[Value]) -> Result<Answer, String> {
    let mut a = Answer::new();
    for s in shows {
        let id = s["id"]
            .as_str()
            .ok_or("an entry without an id")?
            .to_string();
        let occ = s["occluded"]
            .as_bool()
            .ok_or("an entry without `occluded`")?;
        if a.insert(id.clone(), Some((s["screen_bbox"].clone(), occ)))
            .is_some()
        {
            return Err(format!("`{id}` listed twice"));
        }
    }
    for o in out {
        let id = o["id"]
            .as_str()
            .ok_or("an entry without an id")?
            .to_string();
        if a.insert(id.clone(), None).is_some() {
            return Err(format!("`{id}` listed twice"));
        }
    }
    Ok(a)
}

/// The entry point's own answer.
fn reference(c: &Case) -> Answer {
    let (inside, outside) = framing::resolve_targets(&c.grid, &c.cam, c.size, c.size, &c.targets);
    let mut a = Answer::new();
    for r in &inside {
        let b = r.bbox();
        a.insert(
            r.target().id.clone(),
            Some((
                serde_json::json!({ "x": b.x, "y": b.y, "w": b.w, "h": b.h }),
                r.occluded(),
            )),
        );
    }
    for t in outside {
        a.insert(t.id.clone(), None);
    }
    a
}

/// Every consumer's answer to one case, by name.
fn consumers(c: &Case) -> Vec<(&'static str, Result<Answer, String>)> {
    let mut out = Vec::new();

    let (inside, outside) = framing::resolve_targets(&c.grid, &c.cam, c.size, c.size, &c.targets);
    let rgba = vec![0u8; (c.size * c.size * 4) as usize];
    let m = framing::manifest(
        "case",
        "case.png",
        &c.cam,
        &framing::Picture {
            width: c.size,
            height: c.size,
            rgba: &rgba,
        },
        &c.grid,
        framing::Scene {
            pieces: &[],
            inside: &inside,
            outside: &outside,
        },
    );
    let list = |v: &Value| v.as_array().cloned().unwrap_or_default();
    out.push((
        "manifest",
        answer_of(&list(&m["targets"]), &list(&m["out_of_frame"])),
    ));

    let (_, outside, shows) =
        crate::cli::view::snapshot_frame(&c.grid, &c.cam, (c.size, c.size), &c.targets, &|_| None);
    let out_json: Vec<Value> = outside.iter().map(|t| framing::target_json(t)).collect();
    out.push(("snapshot", answer_of(&shows, &out_json)));

    let (_, outside, shows) =
        crate::cli::edit::batch_frame(&c.grid, &c.cam, (c.size, c.size), &c.targets);
    let out_json: Vec<Value> = outside.iter().map(|t| framing::target_json(t)).collect();
    out.push(("edit", answer_of(&shows, &out_json)));

    let (shows, out_json) =
        delvec::compiler::view::review::frame_row(&c.grid, &c.cam, c.size, &c.targets, &[]);
    out.push(("review", answer_of(&shows, &out_json)));

    out
}

/// The stand-back consumer's question for one case: does an eye at the
/// camera's position see the cell above `start`? Asked of the entry point with
/// a camera aimed at that cell, and of the consumer.
fn stand_back_agrees(c: &Case, start: [i32; 3]) -> Result<bool, String> {
    let cell = [start[0], start[1] + 1, start[2]];
    let t = Target::point("anchor-eye".into(), "anchor", String::new(), cell);
    let centre = [
        f64::from(cell[0]) + 0.5,
        f64::from(cell[1]) + 0.5,
        f64::from(cell[2]) + 0.5,
    ];
    let aimed = Camera::looking_at(c.cam.pos, centre, 70.0);
    let (inside, _) = framing::resolve_targets(&c.grid, &aimed, 64, 64, std::slice::from_ref(&t));
    let want = inside.first().is_some_and(|r| !r.occluded());
    let got = delvec::compiler::view::sight::anchor_in_sight(&c.grid, c.cam.pos, start);
    if want == got {
        Ok(got)
    } else {
        Err(format!(
            "sees the cell {cell:?}: {got}, the sight rule says {want}"
        ))
    }
}

/// What one run asked and what differed.
struct Run {
    diffs: Vec<String>,
    /// Questions asked, per consumer.
    asked: BTreeMap<&'static str, usize>,
    /// The entry point's answers over every target: out of frame, in frame and
    /// hidden, in frame and seen.
    kinds: [usize; 3],
    /// The stand-back questions answered seen, of `CASES`.
    stand_back_seen: usize,
}

/// Ask every case of every consumer; the differences name their consumer and
/// case.
fn agreement() -> Run {
    let mut rng = SplitMix(SEED);
    let mut run = Run {
        diffs: Vec::new(),
        asked: BTreeMap::new(),
        kinds: [0; 3],
        stand_back_seen: 0,
    };
    for k in 0..CASES {
        let c = case(&mut rng);
        let want = reference(&c);
        for v in want.values() {
            run.kinds[match v {
                None => 0,
                Some((_, true)) => 1,
                Some((_, false)) => 2,
            }] += 1;
        }
        for (name, got) in consumers(&c) {
            *run.asked.entry(name).or_default() += c.targets.len();
            match got {
                Ok(got) if got == want => {}
                Ok(got) => {
                    let ids: BTreeSet<&String> = want.keys().chain(got.keys()).collect();
                    for id in ids {
                        if want.get(id) != got.get(id) {
                            run.diffs.push(format!(
                                "case {k}: consumer `{name}` answers `{id}` {:?}, the sight rule \
                                 {:?}",
                                got.get(id),
                                want.get(id)
                            ));
                        }
                    }
                }
                Err(e) => run.diffs.push(format!("case {k}: consumer `{name}`: {e}")),
            }
        }
        let start = [
            rng.range(0, EDGE - 1),
            rng.range(0, EDGE - 1),
            rng.range(0, EDGE - 1),
        ];
        *run.asked.entry("stand-back").or_default() += 1;
        match stand_back_agrees(&c, start) {
            Ok(seen) => run.stand_back_seen += usize::from(seen),
            Err(e) => run
                .diffs
                .push(format!("case {k}: consumer `stand-back` {e}")),
        }
    }
    run
}

#[test]
fn every_consumer_of_the_sight_rule_agrees_with_it() {
    let run = agreement();
    let [out, hidden, seen] = run.kinds;
    let per: Vec<String> = run.asked.iter().map(|(k, v)| format!("{k} {v}")).collect();
    println!(
        "one sight rule: {CASES} case(s), {} target question(s) — {out} out of frame, {hidden} \
         in frame and hidden, {seen} in frame and seen; stand-back {} of {CASES} seen; {} of 5 \
         consumer(s) asked: {}",
        out + hidden + seen,
        run.stand_back_seen,
        run.asked.len(),
        per.join(", ")
    );
    // A binding of zero is no agreement: every kind of answer is exercised.
    assert!(out > 0 && hidden > 0 && seen > 0, "{:?}", run.kinds);
    assert!(
        run.stand_back_seen > 0 && run.stand_back_seen < CASES,
        "stand-back answered one way only: {}",
        run.stand_back_seen
    );
    assert_eq!(run.asked.len(), 5, "{:?}", run.asked);
    assert!(
        run.diffs.is_empty(),
        "{} difference(s):\n{}",
        run.diffs.len(),
        run.diffs.join("\n")
    );
}
