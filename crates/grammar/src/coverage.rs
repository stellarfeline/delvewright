//! **Which IR constructs no example exercises** (spec-0033 deliverable C).
//!
//! # What this measures, and the thing it must never be read as
//!
//! `prefab-procedure.md` §3 tells an author to *start from the corpus, never
//! from the schema*. Under that instruction the corpus **is** the language: a
//! construct no example uses does not exist in practice, whatever the IR
//! supports. So this module counts, over the rule library, how many times each
//! IR construct is written, and calls a zero what it is — a finding.
//!
//! It measures **demonstration, not expressiveness.** A green verdict means no
//! part of the language is undemonstrated by an example. It is **not** evidence
//! that an author can build any particular thing, and no document, PR or review
//! may cite it as such. Conflating the two would be this project's own recurring
//! vacuity one level up: a number printed beside the word "pass", believed to
//! have checked something it never looked at. The claim is carried in the report
//! itself ([`Report::measures`]) so it travels with the number rather than
//! living in a doc a reader of the number never opens.
//!
//! # Why the construct list is not a list
//!
//! The measurement in spec-0033 §1 was made by hand once. A hand-kept list of
//! constructs would go stale in exactly the way the hand measurement did, and
//! silently: the next `Node` variant would simply never be counted, so it would
//! read as "not a gap" rather than "not looked at".
//!
//! So the kinds are generated by [`constructs!`] from one list that produces the
//! enum *and* its `ALL` slice, and each kind is assigned by an **exhaustive
//! match** over the IR type ([`NodeKind::of`], [`CondKind::of`],
//! [`PaintKind::of`]). Adding a variant to [`Node`], [`Cond`] or [`Paint`]
//! therefore **fails to compile** until someone classifies it, and a new kind
//! begins life at zero bindings — a surface nothing demonstrates is a finding on
//! the day it lands.
//!
//! # The corpus
//!
//! [`crate::library::PROGRAMS`] — every program `delve-grammar list` names and
//! `delve-grammar show --program <id>` can hand an author. The drowned-bell zone
//! programs are deliberately *not* in it: they are one campaign's composition,
//! unreachable from `list`, so a construct used only there is not demonstrated
//! to anybody. Counting them would turn a gap into a green.

use std::collections::{BTreeMap, BTreeSet};

use serde::Serialize;

use crate::ir::{Cond, Material, Node, Paint, Program};
use crate::library::LibraryProgram;

// ---------------------------------------------------------------------------
// The construct kinds — generated, so the enum and its enumeration cannot drift
// ---------------------------------------------------------------------------

/// Declare a construct-kind enum together with the slice of all its members.
///
/// Both come from one list, so a kind that exists is a kind that is counted:
/// there is no second place to forget to update. What is left hand-written is
/// the `of()` match beside each enum, which is exhaustive over the IR type — the
/// classification the spec requires a person to make.
macro_rules! constructs {
    (
        $(#[$meta:meta])*
        $vis:vis enum $name:ident {
            $( $(#[$vmeta:meta])* $variant:ident = $id:literal ),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
        $vis enum $name {
            $( $(#[$vmeta])* $variant ),+
        }

        impl $name {
            /// Every kind, in declaration order. Generated from the same list as
            /// the variants themselves.
            $vis const ALL: &'static [$name] = &[ $( $name::$variant ),+ ];

            /// The stable id this kind is reported under.
            $vis fn id(self) -> &'static str {
                match self {
                    $( $name::$variant => $id ),+
                }
            }
        }
    };
}

constructs! {
    /// One kind of [`Node`] — a step of a rule body.
    pub enum NodeKind {
        /// [`Node::Fill`].
        Fill = "node:fill",
        /// [`Node::Void`].
        Void = "node:void",
        /// [`Node::Skip`].
        Skip = "node:skip",
        /// [`Node::Call`].
        Call = "node:call",
        /// [`Node::Split`].
        Split = "node:split",
        /// [`Node::Reorient`].
        Reorient = "node:reorient",
        /// [`Node::Mark`].
        Mark = "node:mark",
        /// [`Node::Bind`].
        Bind = "node:bind",
    }
}

impl NodeKind {
    /// Classify one node.
    ///
    /// Exhaustive on purpose: a new [`Node`] variant stops this compiling, and
    /// nothing — not a build, not a test, not the CI step — proceeds until
    /// someone says which kind it is.
    pub fn of(node: &Node) -> NodeKind {
        match node {
            Node::Fill { .. } => NodeKind::Fill,
            Node::Void => NodeKind::Void,
            Node::Skip => NodeKind::Skip,
            Node::Call { .. } => NodeKind::Call,
            Node::Split(_) => NodeKind::Split,
            Node::Reorient { .. } => NodeKind::Reorient,
            Node::Mark { .. } => NodeKind::Mark,
            Node::Bind { .. } => NodeKind::Bind,
        }
    }
}

constructs! {
    /// One kind of [`Cond`] — a rule guard.
    pub enum CondKind {
        /// [`Cond::Always`].
        Always = "cond:always",
        /// [`Cond::Otherwise`].
        Otherwise = "cond:otherwise",
        /// [`Cond::Cmp`].
        Cmp = "cond:cmp",
        /// [`Cond::All`].
        All = "cond:all",
        /// [`Cond::Any`].
        Any = "cond:any",
        /// [`Cond::NoneOf`].
        NoneOf = "cond:none_of",
        /// [`Cond::Orientation`].
        Orientation = "cond:orientation",
    }
}

impl CondKind {
    /// Classify one guard. Exhaustive, for the reason [`NodeKind::of`] is.
    pub fn of(cond: &Cond) -> CondKind {
        match cond {
            Cond::Always => CondKind::Always,
            Cond::Otherwise => CondKind::Otherwise,
            Cond::Cmp { .. } => CondKind::Cmp,
            Cond::All { .. } => CondKind::All,
            Cond::Any { .. } => CondKind::Any,
            Cond::NoneOf { .. } => CondKind::NoneOf,
            Cond::Orientation { .. } => CondKind::Orientation,
        }
    }
}

constructs! {
    /// One kind of [`Paint`] — what a palette role or an inline material
    /// resolves to.
    pub enum PaintKind {
        /// [`Paint::Block`].
        Block = "paint:block",
        /// [`Paint::Mix`] — the only per-cell material variation the language
        /// has.
        Mix = "paint:mix",
    }
}

impl PaintKind {
    /// Classify one paint. Exhaustive, for the reason [`NodeKind::of`] is.
    pub fn of(paint: &Paint) -> PaintKind {
        match paint {
            Paint::Block(_) => PaintKind::Block,
            Paint::Mix(_) => PaintKind::Mix,
        }
    }
}

