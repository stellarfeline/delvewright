/// **Constructs exempt from the required set**, each with the reason it is
/// exempt.
///
/// The required set is *every* construct — the shape `tools/check-dw-codes.py`
/// uses, and for its reason: a required set that is a chosen subset can be made
/// green by shrinking it, which is the one move the debug doctrine forbids. An
/// exemption is therefore a named, reasoned entry here and nowhere else.
///
/// Two ways this list is itself checked, so it cannot rot into a permission
/// slip: an entry naming a construct that does not exist is an error, and an
/// entry naming a construct the corpus *does* demonstrate is an error (delete
/// it — the exemption has been paid off).
///
/// It is empty. That is a statement about the corpus, not about the language.
pub const EXEMPT: &[(&str, &str)] = &[];

/// What a green verdict does and does not say. Carried in every report, printed
/// on every run, and repeated in `docs/reference/grammar.md`, because a number
/// travels further than the page that qualifies it.
pub const MEASURES: &str = "This report measures DEMONSTRATION, not expressiveness. A pass means \
                            no part of the IR is left undemonstrated by the corpus an author is \
                            sent to. It is NOT evidence that an author can build any particular \
                            thing, and no document, PR or review may cite it as such.";

// ---------------------------------------------------------------------------
// The report
// ---------------------------------------------------------------------------

/// One construct's standing in the corpus.
///
/// Shaped like [`crate::gates::Gate`] on purpose — same fields, same meaning of
/// `bound`, same rule that a zero binding is a finding rather than a quiet pass
/// — so a reader who has read one report can read this one.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Construct {
    /// Stable id, e.g. `node:skip`.
    pub id: &'static str,
    /// True when the corpus demonstrates it, or when it is exempt.
    pub pass: bool,
    /// **How many times the corpus writes it.** Zero is a finding.
    pub bound: usize,
    /// Why it is exempt, when it is.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub exempt: Option<&'static str>,
    /// What was found, in one line.
    pub detail: String,
}

/// Numbers with no threshold. Not gates, and deliberately not presented as any.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Measurements {
    /// Programs scanned.
    pub programs: usize,
    /// Rules across those programs.
    pub rules: usize,
    /// Rule alternatives.
    pub alternatives: usize,
    /// [`Node`]s in every rule body.
    pub ir_nodes: usize,
    /// Palette roles bound across the corpus.
    pub palette_roles: usize,
    /// Roles bound to a mix that includes `minecraft:air` — erosion. Reported
    /// rather than gated: "is air a legal member of a mix" is a property of
    /// [`PaintKind::Mix`], which *is* gated, and inventing a second threshold
    /// for how a mix is composed would be a fabricated gate.
    pub mixes_containing_air: usize,
    /// Distinct block states named anywhere in the corpus.
    pub distinct_block_states: usize,
}

/// The whole verdict over one corpus.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Report {
    /// `"pass"` when every required construct is demonstrated, else `"fail"`.
    pub verdict: &'static str,
    /// [`MEASURES`] — what a pass claims, and what it does not.
    pub measures: &'static str,
    /// The program ids scanned, in the order the library lists them.
    pub corpus: Vec<String>,
    /// Every construct, in a fixed order.
    pub constructs: Vec<Construct>,
    /// Numbers, no verdicts.
    pub measurements: Measurements,
    /// Things a reader must be told: a construct nothing demonstrates, an
    /// exemption that has outlived its reason, an empty corpus.
    pub findings: Vec<String>,
}

impl Report {
    /// True when every required construct is demonstrated.
    pub fn is_pass(&self) -> bool {
        self.verdict == "pass"
    }

    /// Canonical pretty JSON with a trailing newline.
    pub fn to_json(&self) -> String {
        let mut s = serde_json::to_string_pretty(self).expect("a coverage report serialises");
        s.push('\n');
        s
    }
}

